let lang = 'en';
export const getLang = () => lang;
export const locale = () => (LANGS.find((l) => l.code === lang) || LANGS[0]).locale;
export function setLang(code) {
  lang = D[code] ? code : 'en';
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  let v = D[lang][key] ?? D.en[key] ?? key;
  if (typeof v === 'object') {
    const form = new Intl.PluralRules(locale()).select(vars.n ?? 0);
    v = v[form] ?? v.other;
  }
  return String(v).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
